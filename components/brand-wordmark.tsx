import { cn } from "@/lib/utils";
import siteConfig from "@/data/site.json";

const artwork = {
  /** The alliance's own SAVR lettering — the default everywhere. */
  alliance: {
    avif: "/brand/savr-wordmark-420.avif 420w, /brand/savr-wordmark-840.avif 840w",
    src: "/brand/savr-wordmark.webp",
    width: 840,
    height: 292,
    alt: `${siteConfig.allianceName} (${siteConfig.callsign})`,
  },
  /** The game's wordmark — used where the guide refers to Last Asylum itself. */
  game: {
    avif: "/brand/la-wordmark-245.avif 245w, /brand/la-wordmark-490.avif 490w",
    src: "/brand/la-wordmark.webp",
    width: 480,
    height: 227,
    alt: "Last Asylum: Plague",
  },
} as const;

/**
 * The site wordmark.
 *
 * Generated by `npm run assets:brand` (alliance art) and `npm run assets:logo`
 * (game art) — AVIF first with a webp fallback. Height, not width, drives the
 * layout so every placement keeps the original lettering proportions.
 */
export function BrandWordmark({
  className,
  sizes = "(min-width: 1024px) 140px, 110px",
  art = "alliance",
  alt,
}: {
  className?: string;
  sizes?: string;
  art?: keyof typeof artwork;
  alt?: string;
}) {
  const source = artwork[art];

  return (
    <picture>
      <source type="image/avif" srcSet={source.avif} sizes={sizes} />
      <img
        src={source.src}
        alt={alt ?? source.alt}
        width={source.width}
        height={source.height}
        decoding="async"
        className={cn("block h-8 w-auto select-none", className)}
      />
    </picture>
  );
}
